CLUB_SCOPE_CASES = [
    ("낚시 동호회 개설 가능한가요?", "낚시"),
    ("헬스 동아리 만들어도 되나요?", "헬스"),
]


def run_evidence_checks():
    """근거 파일 구성과 종목어 도달을 확인하고 실패 건수를 반환합니다."""
    print("[근거 구성] 파일 구성 3문항 · 종목어 도달 2문항")
    failed = 0
    for question, resolved, expected, forbidden in EVIDENCE_CASES:
        files = {item["file"] for item in display_evidence(retrieve(resolved))}
        if files != expected:
            failed += 1
            extra = sorted(files & forbidden)
            print(f"  실패  {question[:44]}")
            print(f"        근거 파일 {sorted(files)}")
            if extra:
                print(f"        무관한 파일 {extra}")
        else:
            print(f"  통과  {question[:44]}")
    for question, term in CLUB_SCOPE_CASES:
        evidence = retrieve(question)
        files = {item["file"] for item in evidence}
        reached = any(term in item["text"] for item in evidence)
        if files != {"동호회 관리 규정.md"} or not reached:
            failed += 1
            print(f"  실패  {question[:44]}")
            print(f"        근거 파일 {sorted(files)} / {term!r} 도달 {reached}")
        else:
            print(f"  통과  {question[:44]}")
    print(f"\n실패 {failed}건\n")
    return failed


CUTOFFS = (1, 3, 5, 10, 20)


def validate_labels(cases, field):
    """라벨이 실제 청크와 맞는지 확인해 오타로 인한 가짜 실패를 막습니다."""
    haystack = [chunk[field] for chunk in load_policy_index()[0]]
    unknown = []
    for question, golds in cases:
        for gold in golds:
            if not any(gold in item for item in haystack):
                unknown.append((question, gold))
    if unknown:
        print(f"청크 {field}와 맞지 않는 라벨이 있습니다. 규정이 바뀌었는지 확인하세요.")
        for question, gold in unknown:
            print(f"  - {gold!r} ← {question}")
        raise SystemExit(2)


def first_gold_rank(question, golds, field):
    """정답 조항이 검색 결과 몇 번째에 나오는지 반환합니다. 없으면 None."""
    for rank, item in enumerate(retrieve(question), 1):
        if any(gold in item.get(field, "") for gold in golds):
            return rank
    return None


def run_set(label, cases, field, verbose):
    """한 세트를 측정해 hit@k와 MRR을 출력합니다."""
    validate_labels(cases, field)
    print(f"[{label}] {len(cases)}문항 · 라벨 기준 {field}")
    ranks = []
    for question, golds in cases:
        rank = first_gold_rank(question, golds, field)
        ranks.append(rank)
        if verbose or rank is None or rank > 5:
            position = f"{rank}위" if rank else "미검색"
            print(f"{position:>6}  {question}")
            if rank is None:
                print(f"        기대 조항: {' | '.join(golds)}")

    total = len(ranks)
    found = [rank for rank in ranks if rank]
    print()
    for cutoff in CUTOFFS:
        hits = sum(1 for rank in found if rank <= cutoff)
        print(f"hit@{cutoff:<2} {hits / total:6.1%}  ({hits}/{total})")
    print(f"MRR    {sum(1 / rank for rank in found) / total:6.3f}")
    print(f"미검색 {total - len(found)}건")
    print()


